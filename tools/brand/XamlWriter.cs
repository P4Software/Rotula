using System.Text;

namespace Rotula.Brand;

/// <summary>Writes Resources/Brand.xaml: the mark as WPF vector images at the three optical sizes the app uses.</summary>
internal static class XamlWriter
{
    /// <summary>Builds the resource dictionary.</summary>
    public static string Dictionary()
    {
        var sb = new StringBuilder();
        sb.AppendLine("<ResourceDictionary xmlns=\"http://schemas.microsoft.com/winfx/2006/xaml/presentation\"");
        sb.AppendLine("                    xmlns:x=\"http://schemas.microsoft.com/winfx/2006/xaml\">");
        sb.AppendLine("  <!--");
        sb.AppendLine("    GENERATED by tools/brand (double-click Regenerate-Brand.cmd). Do not edit by hand: change the drawing in tools/brand and regenerate.");
        sb.AppendLine("    The Rotula mark as vector images. BrandMark24 and BrandMark20 are pixel-grid tuned for the title bars (draw them at exactly");
        sb.AppendLine("    24 / 20 device-independent pixels); BrandMark is the full master drawing for About and the start screen (draw it at 64 or 96).");
        sb.AppendLine("  -->");
        Image(sb, "BrandMark", Layout.ForTile(Layout.Master));
        Image(sb, "BrandMark24", Layout.ForTile(24));
        Image(sb, "BrandMark20", Layout.ForTile(20));
        sb.AppendLine("</ResourceDictionary>");
        return sb.ToString();
    }

    private static void Image(StringBuilder sb, string key, Layout l)
    {
        string box = $"M0 0H{l.Size}V{l.Size}H0Z";
        sb.AppendLine($"  <DrawingImage x:Key=\"{key}\">");
        sb.AppendLine("    <DrawingImage.Drawing>");
        // The clip fixes the image bounds to the whole canvas, so the margin around the tile is kept when it is scaled.
        sb.AppendLine($"      <DrawingGroup ClipGeometry=\"{box}\">");
        sb.AppendLine($"        <GeometryDrawing Geometry=\"{l.BodyPath()}\">");
        sb.AppendLine("          <GeometryDrawing.Brush>");
        sb.AppendLine("            <LinearGradientBrush StartPoint=\"0,0\" EndPoint=\"0,1\">");
        sb.AppendLine($"              <GradientStop Color=\"{Palette.TileTop}\" Offset=\"0\" />");
        sb.AppendLine($"              <GradientStop Color=\"{Palette.TileBottom}\" Offset=\"1\" />");
        sb.AppendLine("            </LinearGradientBrush>");
        sb.AppendLine("          </GeometryDrawing.Brush>");
        sb.AppendLine("        </GeometryDrawing>");
        if (l.Fold > 0)
        {
            sb.AppendLine($"        <GeometryDrawing Brush=\"{Palette.FlapBottom}\" Geometry=\"{l.FlapPath()}\" />");
        }
        sb.AppendLine($"        <GeometryDrawing Brush=\"{Palette.BarLight}\" Geometry=\"{l.BarsPath(false)}\" />");
        sb.AppendLine($"        <GeometryDrawing Brush=\"{Palette.AccentOnDark}\" Geometry=\"{l.BarsPath(true)}\" />");
        sb.AppendLine("      </DrawingGroup>");
        sb.AppendLine("    </DrawingImage.Drawing>");
        sb.AppendLine("  </DrawingImage>");
    }
}
